def build_profile(fields: dict) -> engine.FieldProfile:
    return engine.FieldProfile(
        field_id="parity",
        boundary_source="demo",
        crop_history_summary="parity fixture",
        **{key: fields[key] for key in fields if key != "indicator_statuses"},
        indicator_statuses=fields.get("indicator_statuses", {}),
    )


def summarise(decision: engine.Decision) -> dict:
    """The parts of a Decision the port must reproduce exactly, in compact form."""
    return {
        "o": decision.outcome,
        "r": decision.outcome_reason,
        "u": list(decision.unknowns),
        "s": [
            [s.strategy_id, s.feasibility, [f.rule_id for f in s.findings]]
            for s in decision.strategies
        ],
        "x": [
            [o.outcome_id, o.status, [f.rule_id for f in o.findings], o.statement is not None]
            for o in decision.outcomes
        ],
    }


def export_parity() -> dict:
    values = (True, False, None)
    cases = []
    for name, fields in PROFILES.items():
        profile = build_profile(fields)
        for combo in itertools.product(values, repeat=len(engine.CONSTRAINT_KEYS)):
            constraints = engine.FarmerConstraints.from_mapping(dict(zip(engine.CONSTRAINT_KEYS, combo)))
            cases.append({"p": name, "c": list(combo), "e": summarise(engine.assess(profile, constraints))})
    return {
        "_generated": BANNER,
        "rulesVersion": rules.RULES_VERSION,
        "constraintKeys": list(engine.CONSTRAINT_KEYS),
        "profiles": PROFILES,
        "cases": cases,
    }


def main() -> None:
    OUT.mkdir(parents=True, exist_ok=True)
    rule_table = export_rules()
    parity = export_parity()
    (OUT / "rules.generated.json").write_text(json.dumps(rule_table, indent=2, ensure_ascii=False) + "\n")
    (OUT / "engine-parity.generated.json").write_text(
        json.dumps(parity, separators=(",", ":"), ensure_ascii=False) + "\n"
    )
    print(
        f"export_engine: rules {rules.RULES_VERSION}, {len(rule_table['rules'])} rules, "
        f"{len(rule_table['outcomes'])} outcomes, {len(parity['cases'])} parity cases"
    )


if __name__ == "__main__":
    main()
