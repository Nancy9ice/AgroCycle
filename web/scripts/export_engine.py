#!/usr/bin/env python3
"""Exports DS2's rule table and a parity fixture from the real decision engine.

Why: the web app has no API to call yet (roadmap Phase 10, BE), so `src/features/compare/evaluate.ts`
evaluates the rules in TypeScript. That port must not drift from `engine/decision.py`, and the rule
text must not be retyped. This script writes both from the Python source of truth:

* ``rules.generated.json``: strategy profiles, outcomes, applicability rules, crop claims, standing
  limitations and the required-indicator list, exactly as DS2 wrote them.
* ``engine-parity.generated.json``: what the real engine returns for 7 profiles x 81 constraint
  combinations. A unit test requires the TypeScript port to reproduce it.

Run from anywhere:   npm run sync:engine      (needs Python 3.9+; uses only the standard library)
"""
from __future__ import annotations

import itertools
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "web" / "src" / "features" / "compare" / "data"
sys.path.insert(0, str(ROOT))

from engine import decision as engine
from engine.rules import strategy_rules as rules

BANNER = "Generated by web/scripts/export_engine.py from engine/. Do not edit."
UNKNOWN = engine.UNKNOWN


def jsonable(value):
    """Tuples become lists; the UNKNOWN sentinel becomes null, as it will on the wire."""
    if value is UNKNOWN:
        return None
    if isinstance(value, tuple):
        return [jsonable(item) for item in value]
    return value


def export_rules() -> dict:
    return {
        "_generated": BANNER,
        "rulesVersion": rules.RULES_VERSION,
        "wholeComparisonTarget": rules.WHOLE_COMPARISON_TARGET,
        "severity": list(engine.SEVERITY),
        "requiredIndicators": list(engine.REQUIRED_INDICATORS),
        "standingLimitations": list(engine.STANDING_LIMITATIONS),
        "strategies": [
            {
                "strategy_id": s.strategy_id,
                "label": s.label,
                "rotation": s.rotation,
                "operational_requirements": list(s.operational_requirements),
            }
            for s in rules.STRATEGY_PROFILES
        ],
        "outcomes": [
            {
                "outcome_id": o.outcome_id,
                "label": o.label,
                "claimable": o.claimable,
                "evidence_type": o.evidence_type,
                "source": o.source,
                "statement": o.statement,
                "caution": o.caution,
                "caution_reference": o.caution_reference,
            }
            for o in rules.OUTCOME_EVIDENCE
        ],
        "rules": [
            {
                "rule_id": r.rule_id,
                "outcome_id": r.outcome_id,
                "context_key": r.context_key,
                "operator": r.operator,
                "value": jsonable(r.value),
                "effect": r.effect,
                "condition_text": r.condition_text,
                "rationale": r.rationale,
                "review": r.review,
                "evidence_basis": r.evidence_basis,
                "geography": r.geography,
                "crop": r.crop,
                "management_context": r.management_context,
            }
            for r in rules.APPLICABILITY_RULES
        ],
        "cropClaims": [
            {
                "claim_id": c.claim_id,
                "crop": c.crop,
                "claim": c.claim,
                "status": c.status,
                "note": c.note,
                "geography": c.geography,
                "management_context": c.management_context,
                "applies_when": c.applies_when,
            }
            for c in rules.CROP_CLAIMS
        ],
    }


ALL_OK = {indicator: "ok" for indicator in engine.REQUIRED_INDICATORS}

