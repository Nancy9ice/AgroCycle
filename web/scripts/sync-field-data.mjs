#!/usr/bin/env node
/**
 * Copies the demo-field data the UI needs from the repo's data folder into the web app.
 *
 * Why: Next.js cannot import files from outside `web/`, and the UI should not ship columns
 * it does not use (soil, crop sequences). The output is committed; re-run after DE changes
 * `data/fields/` or `data/reference/`:   npm run sync:data
 */
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..", "..");
const outDir = resolve(
  dirname(fileURLToPath(import.meta.url)),
  "..",
  "src/features/field/data",
);

const read = (relative) => readFileSync(resolve(root, relative), "utf8");

/** Minimal RFC 4180 parser: handles quoted fields containing commas and doubled quotes. */
function parseCsv(text) {
  const rows = [];
  let row = [];
  let cell = "";
  let quoted = false;
  for (let i = 0; i < text.length; i += 1) {
    const char = text[i];
    if (quoted) {
      if (char === '"' && text[i + 1] === '"') {
        cell += '"';
        i += 1;
      } else if (char === '"') {
        quoted = false;
      } else {
        cell += char;
      }
    } else if (char === '"') {
      quoted = true;
    } else if (char === ",") {
      row.push(cell);
      cell = "";
    } else if (char === "\n" || char === "\r") {
      if (char === "\r" && text[i + 1] === "\n") i += 1;
      row.push(cell);
      cell = "";
      if (row.some((value) => value !== "")) rows.push(row);
      row = [];
    } else {
      cell += char;
    }
  }
  if (cell !== "" || row.length > 0) {
    row.push(cell);
    rows.push(row);
  }
  const [header, ...body] = rows;
  return body.map((values) =>
    Object.fromEntries(header.map((name, index) => [name, values[index]])),
  );
}

function fail(message) {
  console.error(`sync-field-data: ${message}`);
  process.exit(1);
}

const notes = new Map(
  parseCsv(read("data/fields/field_selection_notes.csv")).map((row) => [
    row.field_id,
    row,
  ]),
);

const geojson = JSON.parse(read("data/fields/fields.geojson"));
const fields = geojson.features.map((feature) => {
  const p = feature.properties;
  const note = notes.get(p.field_id);
  if (!note) fail(`no row in field_selection_notes.csv for ${p.field_id}`);
  if (feature.geometry.type !== "Polygon") fail(`${p.field_id} is not a Polygon`);
  return {
    id: p.field_id,
    role: p.role,
    county: p.county,
    boundarySource: p.boundary_source,
    provenance: p.provenance,
    domainNote: p.domain_note,
    fieldClass: note.cdl_class,
    coverDetail: p.cover_detail ?? null,
    areaHa: Number(note.area_ha),
    centroid: [Number(note.lon), Number(note.lat)],
    ring: feature.geometry.coordinates[0],
  };
});
fields.sort((a, b) =>
  a.role === b.role ? a.id.localeCompare(b.id) : a.role === "primary" ? -1 : 1,
);

const counties = JSON.parse(
  read("data/reference/story_boone_counties.geojson"),
).features.map((feature) => {
  if (feature.geometry.type !== "Polygon")
    fail(`${feature.properties.county} is not a Polygon`);
  return { county: feature.properties.county, ring: feature.geometry.coordinates[0] };
});

// Inputs for the profile screen: crop history and soil as recorded by the data pipeline.
const profileOutDir = resolve(
  dirname(fileURLToPath(import.meta.url)),
  "..",
  "src/features/profile/data",
);
const profileSource = Object.fromEntries(
  geojson.features.map((feature) => {
    const note = notes.get(feature.properties.field_id);
    if (!/^[A-Z]{11}$/.test(note.crops_2015_2025)) {
      fail(
        `${note.field_id}: crops_2015_2025 must be 11 letters, got "${note.crops_2015_2025}"`,
      );
    }
    return [
      note.field_id,
      {
        cropSequence: note.crops_2015_2025,
        soilSeries: note.soil_series,
        soilMapUnit: note.soil_map_unit,
      },
    ];
  }),
);

mkdirSync(outDir, { recursive: true });
mkdirSync(profileOutDir, { recursive: true });
const banner =
  "Generated by scripts/sync-field-data.mjs from data/fields and data/reference. Do not edit.";
writeFileSync(
  resolve(outDir, "fields.generated.json"),
  `${JSON.stringify({ _generated: banner, fields }, null, 2)}\n`,
);
writeFileSync(
  resolve(outDir, "counties.generated.json"),
  `${JSON.stringify({ _generated: banner, counties }, null, 2)}\n`,
);
writeFileSync(
  resolve(profileOutDir, "profile-source.generated.json"),
  `${JSON.stringify({ _generated: banner, firstYear: 2015, fields: profileSource }, null, 2)}\n`,
);
console.log(
  `sync-field-data: wrote ${fields.length} fields, ${counties.length} counties and profile inputs`,
);
